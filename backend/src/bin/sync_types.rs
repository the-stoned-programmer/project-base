use modern_backend::api::{error::ApiError, health::SystemStatus};
use std::path::Path;
use ts_rs::TS;

macro_rules! export_contracts {
    ($cfg:expr, $($t:ty),* $(,)?) => {
        vec![
            $(
                format!("export {}", <$t>::decl($cfg)),
            )*
        ].join("\n\n")
    };
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out_dir = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "../packages/contracts/src".to_string());

    let out_path = Path::new(&out_dir).join("index.ts");

    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    let cfg = Default::default();
    let declarations = export_contracts!(
        &cfg,
        SystemStatus,
        ApiError,
    );

    let content = format!(
        "// -----------------------------------------------------------------------------\n\
         // AUTO-GENERATED by `scripts/sync-contracts.sh` from Rust domain models.\n\
         // DO NOT EDIT MANUALLY. To update, edit Rust models and re-run sync.\n\
         // -----------------------------------------------------------------------------\n\n\
         {}\n",
        declarations
    );

    std::fs::write(&out_path, content)?;
    println!("Successfully exported TypeScript contracts to {}", out_path.display());

    Ok(())
}
